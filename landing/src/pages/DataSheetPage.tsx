const GROUP: Record<string, string> = { F: "Folhada", M: "Sub-bosque", V: "Matos", H: "Herbáceas" };

interface FuelEntry {
  label: string;
  rothermel?: { group: string; depthM: number; load: number[]; deadMoistExt: number; crown?: unknown; underCanopy?: boolean };
}
/** The fuel table of the Guimarães grid, as the app loads it; null while loading, "error" if it could not be read. */
function useFuelTable(): Record<string, FuelEntry> | null | "error" {
  const [table, setTable] = useState<Record<string, FuelEntry> | null | "error">(null);
  useEffect(() => {
    let cancelled = false;
    fetch("/grids/guimaraes/header.json")
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
      .then((h: { fuelTable: Record<string, FuelEntry> }) => !cancelled && setTable(h.fuelTable))
      .catch(() => !cancelled && setTable("error"));
    return () => {
      cancelled = true;
    };
  }, []);
  return table;
}

